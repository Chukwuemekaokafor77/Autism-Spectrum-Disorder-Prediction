import logging
import os

import joblib
import pandas as pd
from flask import Blueprint, render_template, request
from .model import model, scaler

BASE_DIR = os.path.dirname(os.path.dirname(__file__))
MODEL_DIR = os.path.join(BASE_DIR, 'model')

feature_names_path = os.path.join(MODEL_DIR, 'feature_names.pkl')
model_columns = joblib.load(feature_names_path)

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

main = Blueprint('main', __name__)


def _predict_from_form(form):
    data = {
        'A1': float(form.get('A1', 0)),
        'A2': float(form.get('A2', 0)),
        'A3': float(form.get('A3', 0)),
        'A4': float(form.get('A4', 0)),
        'A5': float(form.get('A5', 0)),
        'A6': float(form.get('A6', 0)),
        'A7': float(form.get('A7', 0)),
        'A8': float(form.get('A8', 0)),
        'A9': float(form.get('A9', 0)),
        'A10': float(form.get('A10', 0)),
        'Age_Mons': float(form.get('Age_Mons', 0)),
        'Sex': form.get('Sex', '0'),
        'Ethnicity': form.get('Ethnicity', 'Others'),
        'Jaundice': form.get('Jaundice', '0'),
        'Family_mem_with_ASD': form.get('Family_mem_with_ASD', '0')
    }

    data_df = pd.DataFrame([data])
    data_df = pd.get_dummies(data_df)
    data_df = data_df.reindex(columns=model_columns, fill_value=0)

    data_scaled = scaler.transform(data_df)
    prob = float(model.predict_proba(data_scaled)[0, 1])

    # Three-band thresholding for clearer communication
    # Note: the underlying dataset is limited and model outputs should be treated as a risk score,
    # not a clinical diagnosis.
    if prob >= 0.9:
        label = 'Positive for ASD Traits'
        explanation = (
            'Based on the answers provided and the underlying dataset, this screening suggests a higher indication of ASD traits. '
            'This tool cannot provide a diagnosis. Please seek a comprehensive evaluation with a qualified healthcare professional '
            'to discuss these results in detail.'
        )
    elif prob <= 0.1:
        label = 'Negative for ASD Traits'
        explanation = (
            'Based on this limited screening and dataset, the tool suggests a lower indication of ASD traits. '
            'However, it cannot rule out ASD or other developmental conditions. If you have any ongoing concerns about your child’s '
            'development, you should still consult a clinician.'
        )
    else:
        label = 'Borderline / Inconclusive for ASD Traits'
        explanation = (
            'The screening result is inconclusive. The pattern of answers does not clearly fall into a higher- or lower-indication band '
            'for ASD traits. Because this tool is based on a specific research dataset and is not a diagnostic instrument, '
            'you may wish to repeat the questionnaire later and/or discuss your concerns directly with a qualified professional.'
        )

    return label, prob, explanation


@main.route('/', methods=['GET', 'POST'])
def index():
    if request.method == 'POST':
        errors = {}

        # Basic validation for Age_Mons
        age_raw = request.form.get('Age_Mons')
        try:
            if age_raw is None or age_raw == '':
                raise ValueError('missing')
            age_val = float(age_raw)
            if age_val < 0:
                errors['Age_Mons'] = 'Please enter an age greater than or equal to 0.'
        except ValueError:
            if 'Age_Mons' not in errors:
                errors['Age_Mons'] = 'Please enter a valid age in months.'

        if errors:
            return render_template('index.html', result=None, probability=None, explanation=None, form_data=request.form, errors=errors)

        try:
            label, prob, explanation = _predict_from_form(request.form)
            logger.info('Prediction made')
            return render_template('index.html', result=label, probability=prob, explanation=explanation, form_data=request.form, errors=None)
        except Exception as e:
            logger.exception('Error during prediction')
            friendly_error = 'We could not complete the prediction. Please check your inputs and try again. If the problem continues, please try again later.'
            return render_template('index.html', result=friendly_error, probability=None, explanation=None, form_data=request.form, errors=None)

    return render_template('index.html', form_data=None, errors=None)


@main.route('/model-image/<filename>', methods=['GET'])
def model_image(filename):
    """Serve confusion matrix and ROC curve images generated by train.py."""
    allowed = {'confusion_matrix.png', 'roc_curve.png'}
    if filename not in allowed:
        return 'Not found', 404
    from flask import send_file
    image_path = os.path.join(MODEL_DIR, filename)
    if not os.path.exists(image_path):
        return 'Not found', 404
    return send_file(image_path, mimetype='image/png')


